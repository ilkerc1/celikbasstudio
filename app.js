let currentLang = localStorage.getItem("celikbas_lang") || "en";
let currentFilter = "all";

// Mini 3x3 Sliding Tile state
let boardState = [1, 2, 3, 4, 5, 6, 7, 8, 0];
let moveCount = 0;

function renderPuzzles() {
  const container = document.getElementById("puzzles-grid-container");
  if (!container) return;

  const filtered = PUZZLES_DATA.filter(
    (item) => currentFilter === "all" || item.category === currentFilter
  );

  container.innerHTML = filtered
    .map(
      (puzzle) => `
      <article class="puzzle-card" id="card-${puzzle.id}">
        <div>
          <div class="puzzle-card-top">
            <span class="puzzle-icon" aria-hidden="true">${puzzle.icon}</span>
            <span class="puzzle-tag">${puzzle.tag[currentLang]}</span>
          </div>
          <h3 style="margin-top: 16px;">${puzzle.title[currentLang]}</h3>
          <p>${puzzle.desc[currentLang]}</p>
        </div>
        <div class="puzzle-meta">
          <span>Mind Nook</span>
          <span>${puzzle.meta[currentLang]}</span>
        </div>
      </article>
    `
    )
    .join("");
}

function isBoardSolved(state) {
  const target = [1, 2, 3, 4, 5, 6, 7, 8, 0];
  return state.every((val, idx) => val === target[idx]);
}

function renderMiniBoard() {
  const grid = document.getElementById("ceramic-tile-grid");
  const counterEl = document.getElementById("move-counter");
  const statusEl = document.getElementById("puzzle-status-msg");
  if (!grid) return;

  counterEl.textContent = String(moveCount);
  const solved = isBoardSolved(boardState);

  grid.innerHTML = boardState
    .map((num, idx) => {
      if (num === 0) {
        return `<button type="button" class="ceramic-tile empty" id="tile-slot-${idx}" disabled aria-label="Empty slot"></button>`;
      }
      const isRightSpot = num === idx + 1;
      return `<button type="button" class="ceramic-tile ${
        isRightSpot ? "correct" : ""
      }" id="tile-slot-${idx}" data-index="${idx}">${num}</button>`;
    })
    .join("");

  if (statusEl) {
    statusEl.textContent = solved
      ? TRANSLATIONS[currentLang].mini_solved_msg
      : TRANSLATIONS[currentLang].mini_playing_msg;
  }

  grid.querySelectorAll(".ceramic-tile:not(.empty)").forEach((btn) => {
    btn.addEventListener("click", () => {
      const idx = Number(btn.getAttribute("data-index"));
      handleTileClick(idx);
    });
  });
}

function getNeighbors(index) {
  const row = Math.floor(index / 3);
  const col = index % 3;
  const neighbors = [];
  if (row > 0) neighbors.push(index - 3);
  if (row < 2) neighbors.push(index + 3);
  if (col > 0) neighbors.push(index - 1);
  if (col < 2) neighbors.push(index + 1);
  return neighbors;
}

function handleTileClick(index) {
  const emptyIndex = boardState.indexOf(0);
  const neighbors = getNeighbors(index);
  if (neighbors.includes(emptyIndex)) {
    boardState[emptyIndex] = boardState[index];
    boardState[index] = 0;
    moveCount += 1;
    renderMiniBoard();
  }
}

function shuffleBoard() {
  boardState = [1, 2, 3, 4, 5, 6, 7, 8, 0];
  let previousEmpty = -1;
  // Perform 24 valid random slides from solved state so it is 100% solvable and cozy
  for (let i = 0; i < 24; i++) {
    const emptyIdx = boardState.indexOf(0);
    const candidates = getNeighbors(emptyIdx).filter((n) => n !== previousEmpty);
    const pick = candidates[Math.floor(Math.random() * candidates.length)];
    boardState[emptyIdx] = boardState[pick];
    boardState[pick] = 0;
    previousEmpty = emptyIdx;
  }
  moveCount = 0;
  renderMiniBoard();
}

function setLanguage(lang) {
  currentLang = lang === "tr" ? "tr" : "en";
  localStorage.setItem("celikbas_lang", currentLang);
  document.documentElement.lang = currentLang;

  const dict = TRANSLATIONS[currentLang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === currentLang);
  });

  renderPuzzles();
  renderMiniBoard();
}

document.addEventListener("DOMContentLoaded", () => {
  // Language switchers
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      setLanguage(btn.getAttribute("data-lang"));
    });
  });

  // Filter buttons
  document.querySelectorAll(".filter-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      currentFilter = btn.getAttribute("data-filter") || "all";
      document.querySelectorAll(".filter-btn").forEach((b) =>
        b.classList.toggle("active", b === btn)
      );
      renderPuzzles();
    });
  });

  // Mini puzzle buttons
  const shuffleBtn = document.getElementById("shuffle-puzzle-btn");
  const resetBtn = document.getElementById("solve-hint-btn");
  if (shuffleBtn) {
    shuffleBtn.addEventListener("click", shuffleBoard);
  }
  if (resetBtn) {
    resetBtn.addEventListener("click", () => {
      boardState = [1, 2, 3, 4, 5, 6, 7, 8, 0];
      moveCount = 0;
      renderMiniBoard();
    });
  }

  // Copy email button
  const copyBtn = document.getElementById("copy-email-btn");
  if (copyBtn) {
    copyBtn.addEventListener("click", () => {
      navigator.clipboard?.writeText("ilker_celikbas@hotmail.com");
      const dict = TRANSLATIONS[currentLang];
      copyBtn.textContent = dict.copied_email;
      setTimeout(() => {
        copyBtn.textContent = TRANSLATIONS[currentLang].copy_email;
      }, 2000);
    });
  }

  shuffleBoard();
  setLanguage(currentLang);
});
