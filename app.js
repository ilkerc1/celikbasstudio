let currentLang = localStorage.getItem("celikbas_lang") || "en";

function setLanguage(lang) {
  currentLang = lang === "tr" ? "tr" : "en";
  localStorage.setItem("celikbas_lang", currentLang);
  document.documentElement.lang = currentLang;

  const dict = TRANSLATIONS[currentLang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === currentLang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      setLanguage(btn.getAttribute("data-lang"));
    });
  });

  const copyBtn = document.getElementById("copy-email-btn");
  if (copyBtn) {
    copyBtn.addEventListener("click", () => {
      navigator.clipboard?.writeText("ilker_celikbas@hotmail.com");
      const dict = TRANSLATIONS[currentLang];
      copyBtn.textContent = dict.copied_email;
      setTimeout(() => {
        copyBtn.textContent = TRANSLATIONS[currentLang].copy_email;
      }, 2000);
    });
  }

  setLanguage(currentLang);
});
